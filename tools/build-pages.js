#!/usr/bin/env node
/*
 * Generates the search-engine parts of the site from index.html, using the
 * settings in tools/seo.config.js:
 *  - the <head> SEO block of every page (title, description, canonical,
 *    hreflang links, Open Graph / Twitter tags, JSON-LD),
 *  - texts written into the HTML between <!--i18n:key--> markers, so they
 *    can be read without JavaScript,
 *  - one page per language (de/, nl/, …; the root page is English) with the
 *    static text translated,
 *  - sitemap.xml.
 *
 * index.html is the template: edit it, then run `node tools/build-pages.js`.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const cfg = require('./seo.config.js');

const ROOT = path.join(__dirname, '..');
const BASE = cfg.base;
const LANGS = cfg.langs; // English first
const OG_LOCALE = { en: 'en_US', de: 'de_DE', nl: 'nl_NL', tr: 'tr_TR', es: 'es_ES' };
const ASSET_RE = cfg.assets; // relative asset paths that need ../ on language pages

const url = (l) => BASE + (l === 'en' ? '' : l + '/');
const escAttr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const decode = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, '\u00a0').replace(/&amp;/g, '&');

function seoBlock(l) {
  const title = cfg.meta.title[l];
  const desc = cfg.meta.description[l];
  const ld = Object.assign({
    '@context': 'https://schema.org',
    '@type': 'WebApplication',
    name: cfg.name,
    alternateName: title,
    url: url(l),
    description: desc,
    applicationCategory: 'EngineeringApplication',
    operatingSystem: 'Any (web browser)',
    browserRequirements: 'Requires JavaScript',
    inLanguage: LANGS,
    isAccessibleForFree: true,
    offers: { '@type': 'Offer', price: '0', priceCurrency: 'EUR' },
    license: 'https://opensource.org/licenses/MIT',
    image: BASE + cfg.ogImage,
    author: { '@type': 'Person', name: 'E. Tozlu', url: 'https://erentozlu.com' },
    publisher: { '@type': 'Organization', name: 'ehcrea', url: 'https://ehcrea.com' },
    codeRepository: cfg.repo,
  }, cfg.featureList ? { featureList: cfg.featureList } : {});
  const lines = [
    `<title>${escText(title)}</title>`,
    `<meta name="description" content="${escAttr(desc)}">`,
    `<link rel="canonical" href="${url(l)}">`,
    ...LANGS.map((x) => `<link rel="alternate" hreflang="${x}" href="${url(x)}">`),
    `<link rel="alternate" hreflang="x-default" href="${url('en')}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="ehcrea">`,
    `<meta property="og:title" content="${escAttr(title)}">`,
    `<meta property="og:description" content="${escAttr(desc)}">`,
    `<meta property="og:url" content="${url(l)}">`,
    `<meta property="og:image" content="${BASE}${cfg.ogImage}">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${escAttr(title)}">`,
    `<meta property="og:locale" content="${OG_LOCALE[l]}">`,
    ...LANGS.filter((x) => x !== l).map((x) => `<meta property="og:locale:alternate" content="${OG_LOCALE[x]}">`),
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escAttr(title)}">`,
    `<meta name="twitter:description" content="${escAttr(desc)}">`,
    `<meta name="twitter:image" content="${BASE}${cfg.ogImage}">`,
    `<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>`,
  ];
  return '<!-- seo: generated by tools/build-pages.js -->\n  ' + lines.join('\n  ') + '\n  <!-- /seo -->';
}

/** Index just past the element that starts at `start` (matching nested tags of the same name). */
function elementEnd(s, start) {
  const name = s.slice(start + 1).match(/^\w+/)[0];
  const re = new RegExp(`<(/?)${name}\\b[^>]*>`, 'g');
  re.lastIndex = start;
  let depth = 0;
  for (let m = re.exec(s); m; m = re.exec(s)) {
    if (m[1]) depth--; else if (!m[0].endsWith('/>')) depth++;
    if (depth === 0) return { innerStart: s.indexOf('>', start) + 1, innerEnd: m.index, end: re.lastIndex };
  }
  return null;
}

/** Translate the static text of a stretch of body markup (no <script> inside). */
function translateMarkup(html, d) {
  // Blocks marked data-i18n-html whose whole (trimmed) markup is a dictionary key.
  let out = '', pos = 0;
  const re = /<\w+[^>]*\sdata-i18n-html(?:="")?[\s>/]/g;
  for (let m = re.exec(html); m; m = re.exec(html)) {
    if (m.index < pos) continue;
    const e = elementEnd(html, m.index);
    if (!e) continue;
    const inner = html.slice(e.innerStart, e.innerEnd);
    const key = inner.trim();
    if (d[key] !== undefined) {
      out += translateMarkup(html.slice(pos, e.innerStart), d) + inner.replace(key, d[key]);
      pos = e.innerEnd;
    }
  }
  html = out + translateTextAndAttrs(html.slice(pos), d);
  return html;
}

function translateTextAndAttrs(html, d) {
  html = html.replace(/>([^<>]+)</g, (m, raw) => {
    const en = decode(raw.trim());
    if (!en || d[en] === undefined) return m;
    const lead = raw.match(/^\s*/)[0], trail = raw.match(/\s*$/)[0];
    return '>' + lead + escText(d[en]) + trail + '<';
  });
  return html.replace(/\s(title|aria-label|placeholder|alt|label)="([^"]*)"/g, (m, a, v) => {
    const en = decode(v);
    return !en || d[en] === undefined ? m : ` ${a}="${escAttr(d[en])}"`;
  });
}

function build(template, l) {
  let s = template;
  s = s.replace(/<!-- seo: generated[\s\S]*?<!-- \/seo -->/, seoBlock(l));
  s = s.replace(/<html lang="\w+"([^>]*) data-page="\w+">/, `<html lang="${l}"$1 data-page="${l}">`);
  const blocks = cfg.blocks ? cfg.blocks() : {};
  s = s.replace(/<!--i18n:(\w+)-->[\s\S]*?<!--\/i18n:\1-->/g, (m, k) => {
    if (!blocks[k]) throw new Error('Unknown text block ' + k);
    return `<!--i18n:${k}-->${blocks[k][l] || blocks[k].en}<!--/i18n:${k}-->`;
  });
  if (l === 'en') return s;
  s = s.replace(ASSET_RE, '$1="../$2');
  const d = cfg.dict(l);
  const i = s.indexOf('<body');
  const head = s.slice(0, i);
  const body = s.slice(i);
  // Translate the markup between scripts; leave scripts and the marked text blocks alone.
  const parts = body.split(/(<script[\s\S]*?<\/script>|<!--i18n:(\w+)-->[\s\S]*?<!--\/i18n:\2-->)/);
  let out = '';
  for (let k = 0; k < parts.length; k += 3) {
    out += translateMarkup(parts[k], d);
    if (parts[k + 1]) out += parts[k + 1];
  }
  return head + out;
}

const template = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
if (!/<!-- seo: generated/.test(template) || !/ data-page="en"/.test(template)) {
  throw new Error('index.html needs the <!-- seo --> markers and data-page="en" on <html>');
}
for (const l of LANGS) {
  const out = build(template, l);
  const file = l === 'en' ? path.join(ROOT, 'index.html') : path.join(ROOT, l, 'index.html');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  console.log('wrote', path.relative(ROOT, file));
}

const today = new Date().toISOString().slice(0, 10);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${LANGS.map((l) => `  <url>
    <loc>${url(l)}</loc>
    <lastmod>${today}</lastmod>
${LANGS.map((x) => `    <xhtml:link rel="alternate" hreflang="${x}" href="${url(x)}"/>`).join('\n')}
    <xhtml:link rel="alternate" hreflang="x-default" href="${url('en')}"/>
  </url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap);
console.log('wrote sitemap.xml');
